def test_data_dto_used_as_return_dto_fallback_over_serialization_plugin() -> None:
    """A declared ``dto`` must be used to serialize the return value even when a serialization plugin
    also supports the return type.

    The explicitly declared ``dto`` takes precedence over a DTO auto-generated by a serialization
    plugin, so the documented ``dto`` -> ``return_dto`` fallback is not shadowed by the plugin.

    See https://github.com/litestar-org/litestar/issues/4906
    """

    class DataDTO(DataclassDTO[Model]):
        config = DTOConfig(exclude={"b"})

    class PluginDTO(DataclassDTO[Model]):
        """Serializes every field, mirroring a plugin-generated DTO without user configuration."""

    class ModelSerializationPlugin(SerializationPlugin):
        def supports_type(self, field_definition: FieldDefinition) -> bool:
            return field_definition.is_subclass_of(Model)

        def create_dto_for_type(self, field_definition: FieldDefinition) -> type[AbstractDTO]:
            return PluginDTO

    @get(dto=DataDTO, signature_types=[Model])
    def handler() -> Model:
        return Model(a=1, b="2")

    with create_test_client(route_handlers=handler, plugins=[ModelSerializationPlugin()]) as client:
        response = client.get("/")
        assert response.status_code == 200
        assert response.json() == {"a": 1}


def test_experimental_codegen_backend_false_is_ignored() -> None:
    with pytest.warns(LitestarDeprecationWarning, match="DTOConfig.experimental_codegen_backend"):
        config = DTOConfig(experimental_codegen_backend=False)
    dto = DataclassDTO[Annotated[Model, config]]

    @post(dto=dto, signature_types=[Model])
    def handler(data: JSONBody[Model]) -> Model:
        assert data == Model(a=1, b="2")
        return data

    with create_test_client(route_handlers=handler) as client:
        response = client.post("/", json={"a": 1, "b": "2"})

    assert response.status_code == 201
    assert response.json() == {"a": 1, "b": "2"}
    assert dto.config.experimental_codegen_backend is None
